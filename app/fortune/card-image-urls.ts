// カードIDに基づいて画像URLを取得する関数
export function getCardImageUrl(cardId: number): string {
  try {
    // 大アルカナ（0-21）
    if (cardId >= 0 && cardId <= 21) {
      return majorArcanaImageUrls[cardId]
    }

    // 小アルカナ - ワンド（22-35）
    if (cardId >= 22 && cardId <= 35) {
      return wandsImageUrls[cardId - 22]
    }

    // 小アルカナ - カップ（36-49）
    if (cardId >= 36 && cardId <= 49) {
      return cupsImageUrls[cardId - 36]
    }

    // 小アルカナ - ソード（50-63）
    if (cardId >= 50 && cardId <= 63) {
      return swordsImageUrls[cardId - 50]
    }

    // 小アルカナ - ペンタクル（64-77）
    if (cardId >= 64 && cardId <= 77) {
      return pentaclesImageUrls[cardId - 64]
    }

    // フォールバック
    return `/placeholder.svg?height=300&width=200&query=${encodeURIComponent(`タロットカード ${cardId}`)}`
  } catch (error) {
    console.error(`カード画像URL生成エラー:`, error)
    return `/placeholder.svg?height=300&width=200&query=エラー`
  }
}

